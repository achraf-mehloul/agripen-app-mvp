export function t(lang: Lang, key: string): string {
  return dict[lang]?.[key] ?? dict.ar[key] ?? key;
}

export function dirOf(lang: Lang): "rtl" | "ltr" {
  return lang === "ar" || lang === "zgh" ? "rtl" : "ltr";
}

/** React hook: returns translator bound to current profile.language and syncs <html lang/dir>. */
export function useT() {
  const auth = useOptionalAuth();
  const lang = (auth?.profile?.language as Lang) || "ar";
  const dir = dirOf(lang);
  useEffect(() => {
    if (typeof document === "undefined") return;
    document.documentElement.setAttribute("lang", lang);
    document.documentElement.setAttribute("dir", dir);
  }, [lang, dir]);
  return {
    lang,
    dir,
    t: (key: string) => t(lang, key),
  };
}
